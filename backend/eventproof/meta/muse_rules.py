"""Muse Spark rule compiler: natural-language rule + scene layout -> validated `VisualRule`.

- Geometry is never generated by the model: zones and lines come from the layout (drawn by the user or
  from the scene); Muse can only reference their ids (JSON-schema enums) and choose operators/thresholds.
- Structured output with `strict: true`. Muse rejects recursive schemas (HTTP 400), so the expression
  is emitted as a flat node list (children = indices) and rebuilt into a tree here; depth and arity are
  then enforced by the rule schema (MAX_DEPTH).
- The model's JSON is data: converted and re-validated through the same Pydantic schema as any rule.
  Invalid output is rejected; one retry feeds the validation error back, then `RuleCompileError`.
- The model may answer `supported=false` (rule not expressible in the DSL) instead of guessing.
- Responses are cached by (text, layout, model, schema version) under `artifacts/muse_cache/`.
"""

from __future__ import annotations

import hashlib
import json
import re
import time
from pathlib import Path

from pydantic import BaseModel, Field, ValidationError

from eventproof.engine.geometry import cross
from eventproof.meta.client import LiveBudget, MetaSettings, get_client
from eventproof.schemas.rules import Line, VisualRule, Zone

SCHEMA_VERSION = "rule-schema/2-nodes"
SCHEMA_VERSION_WITH = "rule-schema/3-with"  # adds WITH (relations to a second tracked concept); used on escalation
# The same two schemas plus a top-level `anchor`: which point of each box zones and lines are tested at. Added after the
# Santos field test (benchmark/real/santos/FINDINGS.md): without it every rule silently used the box centre, even when
# the model's own assumptions said "where the wheels touch the path". Recorded compiles keep their schema version.
SCHEMA_VERSION_ANCHOR = "rule-schema/4-anchor"
SCHEMA_VERSION_WITH_ANCHOR = "rule-schema/5-with-anchor"
# Law mode (schemas 6/7 = 4/5 + provenance): the rule text is a statute quoted verbatim, and every concrete value the
# model puts in the rule must cite an exact quote from it or be declared ASSUMED. Quotes are checked as substrings.
SCHEMA_VERSION_LAW = "rule-schema/6-law"
SCHEMA_VERSION_LAW_WITH = "rule-schema/7-law-with"
PROVENANCE_FIELD = {"type": "array", "description": "one entry per concrete value in the rule", "items": {
    "type": "object", "additionalProperties": False, "required": ["param", "value", "source", "quote", "reason"],
    "properties": {
        "param": {"type": "string", "description": "which value, e.g. 'DWELL.min_ms', 'DWELL.max_speed', 'CROSSES.line', "
                                                   "'CROSSES.direction', 'anchor', 'entity'"},
        "value": {"type": "string"},
        "source": {"type": "string", "enum": ["QUOTED", "ASSUMED"]},
        "quote": {"type": "string", "description": "QUOTED: the exact words of the statute that state this value, "
                                                   "copied verbatim; ASSUMED: empty"},
        "reason": {"type": "string", "description": "ASSUMED: why this value was chosen although the text does not "
                                                    "state it"}}}}
LAW_NOTE = ("\nThe rule text is a statute quoted verbatim. For EVERY concrete value you put in the rule (times, speed "
            "limits for 'still', which line or zone, direction, the measured point, the entity) add a provenance entry: "
            "source QUOTED with the exact words of the statute that state it (copied character for character), or "
            "source ASSUMED with the reason. Never present an assumption as quoted. Behaviour the camera cannot see "
            "(e.g. 'unless directed by a police officer') is listed in assumptions and left out of the rule.")
ANCHOR_FIELD = {"type": "string", "enum": ["center", "bottom_center"],
                "description": "point of each box tested against zones and lines: 'bottom_center' = where the object "
                               "touches the ground (wheels, feet), 'center' = middle of the box"}
CACHE_DIR = Path(__file__).resolve().parents[3] / "artifacts" / "muse_cache"


class LayoutZone(BaseModel):
    zone: Zone
    description: str = ""


class LayoutLine(BaseModel):
    line: Line
    description: str = ""


class Layout(BaseModel):
    zones: list[LayoutZone] = Field(default_factory=list)
    lines: list[LayoutLine] = Field(default_factory=list)


class RuleCompileError(ValueError):
    pass


class UnsupportedRule(RuleCompileError):
    pass


class CompiledRule(BaseModel):
    rule: VisualRule
    assumptions: list[str]
    model: str
    request_ids: list[str]
    attempts: int
    cached: bool
    usage: list[dict]
    raw_output: dict


# ---- schema ---------------------------------------------------------------------------------------


def _obj(props: dict, description: str | None = None) -> dict:
    out = {"type": "object", "properties": props, "required": list(props), "additionalProperties": False}
    if description:
        out["description"] = description
    return out


def _op(name: str) -> dict:
    return {"type": "string", "enum": [name]}


def _nullable(schema: dict) -> dict:
    return {"anyOf": [schema, {"type": "null"}]}


def build_schema(layout: Layout, with_events: bool = False, anchor: bool = False, law: bool = False) -> dict:
    """Constant-size schema: the expression is a flat list of nodes whose children are indices into the
    list. Muse expands `$ref`s, so a recursive grammar unrolled by depth costs exponentially many prompt
    tokens (~195k for 3 levels, measured 2026-10-27); a node list stays small at any depth."""
    zone_ids = [z.zone.id for z in layout.zones] or ["__none__"]
    line_ids = [ln.line.id for ln in layout.lines] or ["__none__"]
    event = {"anyOf": [
        _obj({"op": _op("IN_ZONE"), "zone": {"type": "string", "enum": zone_ids},
              "min_frames": {"type": "integer", "description": "consecutive frames inside, >= 1"}}),
        _obj({"op": _op("DWELL"), "zone": {"type": "string", "enum": zone_ids},
              "min_ms": {"type": "number", "description": "milliseconds continuously inside"},
              "max_speed": _nullable({"type": "number", "description": "0.05 = only while stopped; null = any motion"})}),
        _obj({"op": _op("CROSSES"), "line": {"type": "string", "enum": line_ids},
              "direction": {"type": "string", "enum": ["any", "to_left", "to_right"]}}),
    ] + ([_obj({"op": _op("WITH"),
                "concept": {"type": "string",
                            "description": "short visual noun phrase of the OTHER object, e.g. 'hard hat'"},
                "relation": {"type": "string", "enum": ["near", "on_top"]},
                "max_dist": {"type": "number", "description": "near only: max center distance, fraction of frame width"},
                "min_ms": {"type": "number", "description": "the relation must hold continuously this long (ms)"}})]
         if with_events else [])}
    node = _obj({
        "op": {"type": "string", "enum": ["OCCURS", "BEFORE", "NOT", "AND", "OR", "IMPLIES"]},
        "children": {"type": "array", "items": {"type": "integer"},
                     "description": "indices into nodes: NOT 1, AND/OR 2-8, IMPLIES [premise, conclusion]; else []"},
        "event": _nullable(event) | {"description": "OCCURS only"},
        "first": _nullable(event) | {"description": "BEFORE only"},
        "then": _nullable(event) | {"description": "BEFORE only"},
        "within_ms": _nullable({"type": "number"}) | {"description": "BEFORE only: max ms between; null = no limit"},
    })
    return _obj({
        "supported": {"type": "boolean", "description": "false if the rule cannot be expressed with these operators"},
        "unsupported_reason": {"type": "string", "description": "empty when supported"},
        "rule_id": {"type": "string", "description": "short kebab-case id"},
        "entity_name": {"type": "string", "description": "role in the rule, e.g. 'package'"},
        "entity_concept": {"type": "string", "description": "short visual noun phrase for the detector, e.g. 'blue box'"},
        "nodes": {"type": "array", "items": node, "description": "expression nodes; children refer to indices"},
        "root": {"type": "integer", "description": "index of the root node"},
        "normalized_explanation": {"type": "string", "description": "one sentence, what exactly is checked"},
        "assumptions": {"type": "array", "items": {"type": "string"},
                        "description": "every interpretation choice not literally stated in the rule"},
    } | ({"anchor": ANCHOR_FIELD} if anchor else {}) | ({"provenance": PROVENANCE_FIELD} if law else {}))


# ---- prompt ---------------------------------------------------------------------------------------


def _directions(line: Line) -> str:
    """Translate to_left/to_right (judged walking a->b) into image directions the model can reason about."""
    mx, my = (line.a[0] + line.b[0]) / 2, (line.a[1] + line.b[1]) / 2
    out = []
    for name, (dx, dy) in (("rightwards (+x)", (1, 0)), ("leftwards (-x)", (-1, 0)),
                           ("downwards (+y)", (0, 1)), ("upwards (-y)", (0, -1))):
        side = cross(line.a, line.b, (mx + 1e-3 * dx, my + 1e-3 * dy))
        if side:
            out.append(f"moving {name} across it = {'to_right' if side > 0 else 'to_left'}")
    return "; ".join(out)


SYSTEM = """You compile a natural-language video rule into EventProof's rule DSL. Output only the JSON the schema allows.
Each tracked object of the entity is checked independently; the rule must hold for every object.
Events (per object): IN_ZONE(zone, min_frames); DWELL(zone, min_ms, max_speed) = continuously inside >= min_ms
(max_speed 0.05 = only while stopped/still; null = any motion); CROSSES(line, direction).
Expressions: OCCURS(event); BEFORE(first, then, within_ms) = first happens and precedes the first occurrence of then;
NOT, AND, OR (2-8 args), IMPLIES(premise, conclusion). Keep the expression as shallow as possible.
Write the expression as a node list: each node has op, children (indices of other nodes), and only the fields
its op uses (others null). Every node is used exactly once; root is the top node's index.
Idiom: "every X must do A before B" -> IMPLIES(OCCURS(B), BEFORE(A, B)), so objects that never do B pass.
Times are milliseconds. Use only the zone/line ids listed. Never invent geometry.
If the rule needs anything else (other attributes, counting, people, colours of other objects, speed limits...)
set supported=false, explain in unsupported_reason, and still fill the other fields minimally.
List every interpretation choice in assumptions."""


SYSTEM_WITH = SYSTEM.replace(
    "If the rule needs anything else (other attributes, counting, people, colours of other objects, speed limits...)",
    "Event WITH(concept, relation, max_dist, min_ms) relates the object to an object of ANOTHER visual concept tracked "
    "separately: 'near' = centers within max_dist (fraction of frame width), 'on_top' = the other object sits over the top "
    "of this object's box (e.g. a hard hat on a person); it must hold continuously for min_ms. Use it for rules about "
    "wearing or carrying something visible, or keeping distance from another kind of object.\n"
    "If the rule needs anything else (counting, colours, speed limits, identity...)")


ANCHOR_NOTE = ("\nBefore zones and lines are tested, each object's box is reduced to one point, the anchor: "
               "'bottom_center' is where the object touches the ground (wheels, feet), 'center' is the middle of the box. "
               "Pick the point the zones and lines were drawn for, from their descriptions and the rule, and state the "
               "choice in assumptions.")


def user_prompt(text: str, layout: Layout) -> str:
    zones = "\n".join(f"- zone '{z.zone.id}': {z.description or '(no description)'}" for z in layout.zones) or "- (none)"
    lines = "\n".join(f"- line '{ln.line.id}': {ln.description or '(no description)'}; {_directions(ln.line)}"
                      for ln in layout.lines) or "- (none)"
    return f"Zones:\n{zones}\nLines:\n{lines}\n\nRule:\n{text.strip()}"


# ---- conversion -----------------------------------------------------------------------------------


def _strip_nulls(x):
    if isinstance(x, dict):
        return {k: _strip_nulls(v) for k, v in x.items() if v is not None}
    if isinstance(x, list):
        return [_strip_nulls(v) for v in x]
    return x


def _slug(s: str) -> str:
    s = re.sub(r"[^a-z0-9_\-]+", "-", s.lower()).strip("-")
    return (s if s[:1].isalpha() else f"rule-{s}")[:60] or "rule"


def nodes_to_expr(nodes: list[dict], root: int) -> dict:
    """Rebuild the expression tree from the node list. Each node may be used once (a tree, no sharing or
    cycles); unused nodes are an error so nothing the model wrote is silently ignored."""
    used: set[int] = set()

    def build(i: int) -> dict:
        if not isinstance(i, int) or not 0 <= i < len(nodes):
            raise RuleCompileError(f"node index {i} out of range")
        if i in used:
            raise RuleCompileError(f"node {i} referenced twice (expression must be a tree)")
        used.add(i)
        n = nodes[i]
        op, kids = n["op"], n.get("children") or []
        if kids and op in ("OCCURS", "BEFORE"):
            raise RuleCompileError(f"{op} node {i} must not have children")
        if op == "OCCURS":
            return {"op": op, "event": n.get("event")}
        if op == "BEFORE":
            return {"op": op, "first": n.get("first"), "then": n.get("then"), "within_ms": n.get("within_ms")}
        if op == "NOT":
            if len(kids) != 1:
                raise RuleCompileError(f"NOT node {i} needs exactly 1 child")
            return {"op": op, "arg": build(kids[0])}
        if op == "IMPLIES":
            if len(kids) != 2:
                raise RuleCompileError(f"IMPLIES node {i} needs [premise, conclusion]")
            return {"op": op, "premise": build(kids[0]), "conclusion": build(kids[1])}
        return {"op": op, "args": [build(k) for k in kids]}  # AND / OR: arity checked by the schema model

    tree = build(root)
    if unused := set(range(len(nodes))) - used:
        raise RuleCompileError(f"unused nodes {sorted(unused)}")
    return tree


def _norm(t: str) -> str:
    return " ".join(t.replace("\u2013", "-").replace("\u2014", "-").split()).lower()


def check_quotes(out: dict, statute: str) -> None:
    """Law mode: every QUOTED provenance entry must be an exact (whitespace- and case-normalised) substring of the
    statute; otherwise the compile is rejected (the model may not invent law)."""
    bad = [p["param"] for p in out.get("provenance", [])
           if p.get("source") == "QUOTED" and (not p.get("quote", "").strip() or _norm(p["quote"]) not in _norm(statute))]
    if bad:
        raise RuleCompileError(f"provenance quotes not found verbatim in the statute for: {', '.join(bad)}")


def to_visual_rule(out: dict, layout: Layout) -> VisualRule:
    """Muse output -> VisualRule. Raises UnsupportedRule, RuleCompileError or pydantic ValidationError."""
    if not out.get("supported", False):
        raise UnsupportedRule(out.get("unsupported_reason") or "model marked the rule as unsupported")
    return VisualRule.model_validate({
        "rule_id": _slug(out["rule_id"]),
        "entity": {"name": out["entity_name"], "concept": out["entity_concept"]},
        "zones": [z.zone.model_dump() for z in layout.zones],
        "lines": [ln.line.model_dump() for ln in layout.lines],
        "check": _strip_nulls(nodes_to_expr(out["nodes"], out["root"])),
        "normalized_explanation": out.get("normalized_explanation", "")[:600],
    } | ({"params": {"anchor": out["anchor"]}} if out.get("anchor") else {}))


# ---- compiler -------------------------------------------------------------------------------------


class MuseRuleCompiler:
    def __init__(self, settings: MetaSettings | None = None, cache_dir: Path | None = None, max_attempts: int = 2,
                 budget: LiveBudget | None = None, allow_with: bool = True, anchor_field: bool = False,
                 law: bool = False):
        self.settings = settings or MetaSettings.from_env()
        self.cache_dir, self.max_attempts = cache_dir or CACHE_DIR, max_attempts
        self.budget = budget  # None: no cap (CLI/bench runs by the participant); the API always passes one
        self.allow_with = allow_with  # escalate to the WITH schema when the base schema cannot express the rule
        self.anchor_field = anchor_field  # schemas 4/5: the model also picks the anchor (new compiles only)
        self.law = law  # schemas 6/7: statute text, every value QUOTED (verified substring) or ASSUMED
        self.live_calls = 0

    def _key(self, text: str, layout: Layout, version: str = SCHEMA_VERSION) -> str:
        blob = json.dumps([text.strip(), layout.model_dump(mode="json"), self.settings.muse_model, version],
                          sort_keys=True)
        return hashlib.sha256(blob.encode()).hexdigest()

    def _call(self, messages: list[dict], schema: dict) -> tuple[dict, str, dict]:
        client = get_client(self.settings)  # raises MetaApiUnavailable without a key
        if self.budget:
            self.budget.take("rule compile")
        resp = client.chat.completions.create(
            model=self.settings.muse_model, messages=messages,
            response_format={"type": "json_schema",
                             "json_schema": {"name": "eventproof_rule", "schema": schema, "strict": True}})
        self.live_calls += 1
        content = resp.choices[0].message.content or ""
        try:
            parsed = json.loads(content)
        except json.JSONDecodeError as e:
            raise RuleCompileError(f"model returned non-JSON content: {e}") from None
        return parsed, resp.id, resp.usage.model_dump() if resp.usage else {}

    def compile(self, text: str, layout: Layout) -> CompiledRule:
        """Base schema first (keeps every recorded compile valid); if the model says the rule is not expressible
        there and `allow_with`, one escalation to the schema with WITH events."""
        base, wide = ((SCHEMA_VERSION_LAW, SCHEMA_VERSION_LAW_WITH) if self.law
                      else (SCHEMA_VERSION_ANCHOR, SCHEMA_VERSION_WITH_ANCHOR) if self.anchor_field
                      else (SCHEMA_VERSION, SCHEMA_VERSION_WITH))
        try:
            return self._compile(text, layout, base)
        except UnsupportedRule:
            if not self.allow_with:
                raise
            return self._compile(text, layout, wide)

    def _compile(self, text: str, layout: Layout, version: str) -> CompiledRule:
        cpath = self.cache_dir / f"{self._key(text, layout, version)}.json"
        if cpath.exists():
            c = json.loads(cpath.read_text())
            return CompiledRule(rule=to_visual_rule(c["raw_output"], layout), assumptions=c["raw_output"]["assumptions"],
                                model=c["model"], request_ids=c["request_ids"], attempts=c["attempts"], cached=True,
                                usage=c["usage"], raw_output=c["raw_output"])
        refusal = self.cache_dir / f"{self._key(text, layout, version)}.unsupported.json"
        if refusal.exists():  # a recorded "not expressible" answer is also replayed (it decides the escalation)
            raise UnsupportedRule(json.loads(refusal.read_text())["reason"])
        with_events = version in (SCHEMA_VERSION_WITH, SCHEMA_VERSION_WITH_ANCHOR, SCHEMA_VERSION_LAW_WITH)
        law = version in (SCHEMA_VERSION_LAW, SCHEMA_VERSION_LAW_WITH)
        anchor = law or version in (SCHEMA_VERSION_ANCHOR, SCHEMA_VERSION_WITH_ANCHOR)
        schema = build_schema(layout, with_events, anchor, law)
        system = (SYSTEM_WITH if with_events else SYSTEM) + (ANCHOR_NOTE if anchor else "") + (LAW_NOTE if law else "")
        messages = [{"role": "system", "content": system},
                    {"role": "user", "content": user_prompt(text, layout)}]
        ids, usage, t0 = [], [], time.monotonic()
        for attempt in range(1, self.max_attempts + 1):
            out, rid, u = self._call(messages, schema)
            ids.append(rid)
            usage.append(u)
            try:
                rule = to_visual_rule(out, layout)
                if law:
                    check_quotes(out, text)
            except UnsupportedRule as e:
                self.cache_dir.mkdir(parents=True, exist_ok=True)
                refusal.write_text(json.dumps({"reason": str(e), "request_ids": ids, "model": self.settings.muse_model,
                                               "text": text, "schema": version}, indent=2))
                raise
            except (ValidationError, RuleCompileError) as e:
                errors = ("; ".join(f"{'.'.join(map(str, er['loc']))}: {er['msg']}" for er in e.errors()[:5])
                          if isinstance(e, ValidationError) else str(e))
                if attempt == self.max_attempts:
                    raise RuleCompileError(f"invalid rule after {attempt} attempts: {errors}") from None
                messages += [{"role": "assistant", "content": json.dumps(out)},
                             {"role": "user", "content": f"That rule failed validation: {errors}. Return a corrected rule."}]
                continue
            self.cache_dir.mkdir(parents=True, exist_ok=True)
            cpath.write_text(json.dumps({"raw_output": out, "model": self.settings.muse_model, "request_ids": ids,
                                         "schema": version,
                                         "attempts": attempt, "usage": usage, "text": text,
                                         "latency_s": round(time.monotonic() - t0, 2)}, indent=2))
            return CompiledRule(rule=rule, assumptions=out.get("assumptions", []), model=self.settings.muse_model,
                                request_ids=ids, attempts=attempt, cached=False, usage=usage, raw_output=out)
        raise AssertionError("unreachable")


def main() -> None:
    """Compile a benchmark file of natural-language rules with live Muse Spark (cached) and report.

    uv run python -m eventproof.meta.muse_rules ../benchmark/rules/nl_rules_v1.json --out ../benchmark/rules/report.json
    """
    import argparse
    from collections import Counter

    from eventproof.challenge.families import FAMILIES
    from eventproof.challenge.runner import DEV_SEEDS, run_case

    ap = argparse.ArgumentParser()
    ap.add_argument("bench", type=Path)
    ap.add_argument("--out", type=Path)
    args = ap.parse_args()
    bench = json.loads(args.bench.read_text())
    layout = Layout.model_validate(bench["layout"])
    comp = MuseRuleCompiler()
    dev = [FAMILIES[f](s) for f in sorted(FAMILIES) for s in DEV_SEEDS]
    rows = []
    for item in bench["rules"]:
        row = {"id": item["id"], "text": item["text"], "expect": item["expect"]}
        try:
            res = comp.compile(item["text"], layout)
        except UnsupportedRule as e:
            row |= {"result": "unsupported", "reason": str(e)}
        except RuleCompileError as e:
            row |= {"result": "rejected_invalid", "reason": str(e)}
        else:
            outcomes = Counter(run_case(s, res.rule).outcome for s in dev)
            row |= {"result": "compiled", "rule": json.loads(res.rule.canonical_json()), "rule_hash": res.rule.rule_hash(),
                    "assumptions": res.assumptions, "attempts": res.attempts, "request_ids": res.request_ids,
                    "cached": res.cached, "usage": [{k: u.get(k) for k in ("prompt_tokens", "completion_tokens")}
                                                    for u in res.usage],
                    "dev_outcomes_mock_perception": dict(outcomes)}
        rows.append(row)
        print(f"{row['id']:14} {row['result']:16} {row.get('dev_outcomes_mock_perception', row.get('reason', ''))}")
    report = {"model": comp.settings.muse_model, "schema_version": SCHEMA_VERSION, "live_calls_this_run": comp.live_calls,
              "dev_scenes": len(dev), "perception_for_dev_outcomes": "mock (NOT SAM)", "rules": rows}
    if args.out:
        args.out.write_text(json.dumps(report, indent=2) + "\n")


if __name__ == "__main__":
    main()
